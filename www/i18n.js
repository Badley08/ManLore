class I18n {
    constructor() {
        this.lang = localStorage.getItem('manlore_lang') || 'fr';
        this.fallback = 'fr';
    }

    get currentLang() {
        return this.lang;
    }

    setLang(lang) {
        if (TRANSLATIONS[lang]) {
            this.lang = lang;
            localStorage.setItem('manlore_lang', lang);
            this.applyAll();
            window.dispatchEvent(new CustomEvent('languageChanged', { detail: { lang } }));
        }
    }

    t(key, vars = {}) {
        const dict = TRANSLATIONS[this.lang] || TRANSLATIONS[this.fallback];
        const fallbackDict = TRANSLATIONS[this.fallback];
        let str = dict[key] || fallbackDict[key] || key;

        // Replace {var} placeholders
        Object.keys(vars).forEach(k => {
            str = str.replace(new RegExp(`\\{${k}\\}`, 'g'), vars[k]);
        });
        return str;
    }

    tType(type) {
        if (!type) return '—';
        const key = 'type.' + type.toLowerCase().replace(/\s+/g, '');
        return this.t(key);
    }

    tStatus(status) {
        if (!status) return '—';
        const normalized = status.toLowerCase()
            .replace(/\s+/g, '-')
            .normalize('NFD')
            .replace(/[\u0300-\u036f]/g, '');
        return this.t('status.' + normalized);
    }

    applyAll() {
        // Update all elements with data-i18n attribute
        document.querySelectorAll('[data-i18n]').forEach(el => {
            const key = el.getAttribute('data-i18n');
            const attr = el.getAttribute('data-i18n-attr');
            const val = this.t(key);
            if (attr) {
                el.setAttribute(attr, val);
            } else {
                el.textContent = val;
            }
        });

        // Update placeholders
        document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
            el.placeholder = this.t(el.getAttribute('data-i18n-placeholder'));
        });

        // Update html lang attribute
        document.documentElement.lang = this.lang;

        // Update active lang button
        document.querySelectorAll('.lang-btn').forEach(btn => {
            btn.classList.toggle('active', btn.dataset.lang === this.lang);
        });

        console.log('[i18n] Language applied:', this.lang);
    }
}

const i18n = new I18n();
console.log('[i18n] Module loaded, language:', i18n.lang);
